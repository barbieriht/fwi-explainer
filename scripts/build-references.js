#!/usr/bin/env node
/*
 * Regenerates the bibliography in references.html from the reference data and
 * the citations actually used in the site's pages (data-cite="id").
 *
 *   node scripts/build-references.js          rewrite references.html
 *   node scripts/build-references.js --check  exit 1 if it is out of date
 *
 * Fails if a page cites an id that is not in the reference data.
 */
'use strict';

const fs = require('fs');
const path = require('path');

const ROOT = path.join(__dirname, '..');
const DATA_FILES = ['assets/data/foundational-references.json'];
const PAGES = [
  'index.html', 'forward-modeling.html', 'inverse-problem.html', 'deep-learning.html',
  'research-landscape.html', 'open-problems.html',
];
const TARGET = 'references.html';
const START = '<!-- references:start (generated by scripts/build-references.js; do not edit) -->';
const END = '<!-- references:end -->';
const CITE_PATTERN = /data-cite="([^"]+)"/g;

function escapeHtml(text) {
  return String(text).replace(/[&<>"]/g, function (c) {
    return { '&': '&amp;', '<': '&lt;', '>': '&gt;', '"': '&quot;' }[c];
  });
}

function loadReferences() {
  const byId = new Map();
  DATA_FILES.forEach(function (file) {
    const data = JSON.parse(fs.readFileSync(path.join(ROOT, file), 'utf8'));
    data.references.forEach(function (ref) {
      ['id', 'authors', 'year', 'title', 'venue'].forEach(function (key) {
        if (!ref[key]) throw new Error(file + ': reference ' + (ref.id || '?') + ' is missing "' + key + '"');
      });
      if (byId.has(ref.id)) throw new Error('duplicate reference id: ' + ref.id);
      byId.set(ref.id, ref);
    });
  });
  return byId;
}

function collectCitations() {
  const citedBy = new Map(); // id -> [page, ...]
  PAGES.forEach(function (page) {
    const html = fs.readFileSync(path.join(ROOT, page), 'utf8');
    for (const match of html.matchAll(CITE_PATTERN)) {
      const pages = citedBy.get(match[1]) || [];
      if (!pages.includes(page)) pages.push(page);
      citedBy.set(match[1], pages);
    }
  });
  return citedBy;
}

function pageTitle(page) {
  const html = fs.readFileSync(path.join(ROOT, page), 'utf8');
  const m = /<h1>(.*?)<\/h1>/.exec(html);
  return m ? m[1] : page;
}

function formatEntry(ref, pages) {
  const details = [ref.volume, ref.issue ? '(' + ref.issue + ')' : '', ref.pages ? ', ' + ref.pages : '']
    .join('').trim();
  const link = ref.doi
    ? ' <a href="https://doi.org/' + escapeHtml(ref.doi) + '">doi:' + escapeHtml(ref.doi) + '</a>'
    : (ref.url ? ' <a href="' + escapeHtml(ref.url) + '">link</a>' : '');
  const usedOn = pages.map(function (p) {
    return '<a href="' + p + '">' + escapeHtml(pageTitle(p)) + '</a>';
  }).join(', ');
  return [
    '      <li id="' + escapeHtml(ref.id) + '">',
    '        ' + escapeHtml(ref.authors.join(', ')) + ' (' + ref.year + '). ' + escapeHtml(ref.title) +
      '. <em>' + escapeHtml(ref.venue) + '</em>' + (details ? ' ' + escapeHtml(details) : '') + '.' + link,
    '        <span class="cited-on">Cited on: ' + usedOn + '</span>',
    '      </li>',
  ].join('\n');
}

function render() {
  const refs = loadReferences();
  const citedBy = collectCitations();
  const missing = Array.from(citedBy.keys()).filter(function (id) { return !refs.has(id); });
  if (missing.length) throw new Error('cited but not in reference data: ' + missing.join(', '));
  const entries = Array.from(citedBy.keys()).map(function (id) { return refs.get(id); })
    .sort(function (a, b) { return a.authors[0].localeCompare(b.authors[0]) || a.year - b.year; });
  const list = entries.length
    ? '    <ol class="bibliography">\n' + entries.map(function (r) { return formatEntry(r, citedBy.get(r.id)); }).join('\n') + '\n    </ol>'
    : '    <p>No citations yet.</p>';
  const html = fs.readFileSync(path.join(ROOT, TARGET), 'utf8');
  const start = html.indexOf(START);
  const end = html.indexOf(END);
  if (start < 0 || end < start) throw new Error(TARGET + ' is missing the generated-section markers');
  return html.slice(0, start + START.length) + '\n' + list + '\n    ' + html.slice(end);
}

function main() {
  const next = render();
  const current = fs.readFileSync(path.join(ROOT, TARGET), 'utf8');
  if (process.argv.includes('--check')) {
    if (next !== current) {
      console.error(TARGET + ' is out of date; run: node scripts/build-references.js');
      process.exit(1);
    }
    return;
  }
  fs.writeFileSync(path.join(ROOT, TARGET), next);
}

if (require.main === module) main();
module.exports = { render: render, loadReferences: loadReferences, collectCitations: collectCitations };
